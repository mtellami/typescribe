import {
  fetchTranscript,
  listLanguages,
  YoutubeTranscriptInvalidVideoIdError,
  YoutubeTranscriptVideoUnavailableError,
  YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptNotAvailableError,
  YoutubeTranscriptDisabledError,
  type CaptionTrackInfo,
} from 'youtube-transcript-plus';
import { AppError } from '@/lib/errors';
import type { TranscriptResult } from './types';

const USER_AGENT = process.env.TRANSCRIPT_USER_AGENT || undefined;
const MAX_DURATION_SECONDS = Number(
  process.env.IMPORT_MAX_DURATION_SECONDS ?? 3600,
);

function pickTrack(
  tracks: CaptionTrackInfo[],
  requestedLang: string,
): CaptionTrackInfo | undefined {
  const requested = requestedLang.toLowerCase();
  const primary = requested.split('-')[0];
  return (
    tracks.find((t) => t.languageCode.toLowerCase() === requested) ??
    tracks.find(
      (t) => t.languageCode.toLowerCase().split('-')[0] === primary,
    ) ??
    tracks.find((t) => !t.isAutoGenerated) ??
    tracks[0]
  );
}

function pickThumbnail(
  thumbnails:
    Array<{ url: string; width?: number; height?: number }> | undefined,
  videoId: string,
): string {
  const best = [...(thumbnails ?? [])].sort(
    (a, b) =>
      (b.width ?? 0) * (b.height ?? 0) - (a.width ?? 0) * (a.height ?? 0),
  )[0];
  return best?.url ?? `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
}

function mapTranscriptError(error: unknown): never {
  if (error instanceof AppError) throw error;
  if (error instanceof YoutubeTranscriptInvalidVideoIdError) {
    throw new AppError('INVALID_URL', 400, 'Invalid YouTube video ID.');
  }
  if (error instanceof YoutubeTranscriptVideoUnavailableError) {
    throw new AppError('VIDEO_UNAVAILABLE', 404, 'This video is unavailable.');
  }
  if (error instanceof YoutubeTranscriptNotAvailableError) {
    throw new AppError('NO_CAPTIONS', 422, 'This video has no captions.');
  }
  if (error instanceof YoutubeTranscriptDisabledError) {
    throw new AppError(
      'NO_CAPTIONS',
      422,
      'Captions are disabled for this video.',
    );
  }
  if (error instanceof YoutubeTranscriptTooManyRequestError) {
    throw new AppError(
      'FETCH_FAILED',
      502,
      'YouTube rate-limited the request. Try again later.',
    );
  }
  if (error instanceof Error && error.name === 'AbortError') {
    throw new AppError(
      'FETCH_FAILED',
      502,
      'The transcript request timed out.',
    );
  }
  throw new AppError(
    'FETCH_FAILED',
    502,
    'Could not fetch captions for this video.',
  );
}

export async function fetchVideoTranscript(
  videoId: string,
  requestedLang: string,
): Promise<TranscriptResult> {
  try {
    const tracks = await listLanguages(videoId, {
      userAgent: USER_AGENT,
      retries: 2,
      retryDelay: 500,
      signal: AbortSignal.timeout(15_000),
    });

    const track = pickTrack(tracks, requestedLang);
    if (!track) {
      throw new AppError('NO_CAPTIONS', 422, 'This video has no captions.');
    }

    const result = await fetchTranscript(videoId, {
      lang: track.languageCode,
      userAgent: USER_AGENT,
      videoDetails: true,
      retries: 2,
      retryDelay: 500,
      signal: AbortSignal.timeout(15_000),
    });

    if (Array.isArray(result)) {
      throw new AppError(
        'FETCH_FAILED',
        502,
        'Transcript metadata was missing.',
      );
    }

    const details = result.videoDetails;
    if (details.isLiveContent) {
      throw new AppError(
        'VIDEO_UNAVAILABLE',
        404,
        'Live videos are not supported.',
      );
    }

    const durationSeconds = Number(details.lengthSeconds);
    if (
      Number.isFinite(durationSeconds) &&
      durationSeconds > MAX_DURATION_SECONDS
    ) {
      throw new AppError('TOO_LONG', 422, 'This video is too long.');
    }

    return {
      track: {
        lang: track.languageCode,
        kind: track.isAutoGenerated ? 'auto' : 'manual',
        label: track.languageName,
      },
      details: {
        title: details.title,
        channel: details.author,
        thumbnail: pickThumbnail(details.thumbnails, videoId),
        durationSeconds: Number.isFinite(durationSeconds) ? durationSeconds : 0,
        isLive: details.isLiveContent,
      },
      cues: result.segments.map((segment) => ({
        startMs: Math.round(segment.offset * 1000),
        endMs: Math.round((segment.offset + segment.duration) * 1000),
        text: segment.text,
      })),
    };
  } catch (error) {
    mapTranscriptError(error);
  }
}
